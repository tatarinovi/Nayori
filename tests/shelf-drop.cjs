const fs = require('fs'), vm = require('vm'), assert = require('assert')
const api = {Qt: {btoa: s => Buffer.from(s, 'binary').toString('base64')}}
vm.createContext(api)
vm.runInContext(fs.readFileSync('surfaces/island/ShelfDrop.js', 'utf8'), api)
const offer = (data, values = {}) => Object.assign({formats: Object.keys(data), getDataAsString: f => data[f] || '', getDataAsArrayBuffer: f => Buffer.from(data[f] || '')}, values)
assert(api.supports(offer({'text/plain': 'hello'})))
assert(!api.supports(offer({'application/x-secret': 'secret'})))
assert.equal(api.read(offer({'text/plain': 'hello'})).text, 'hello')
assert.equal(api.read(offer({'text/uri-list': '#comment\r\nfile:///tmp/a%23b.txt\r\n'})).urls[0], 'file:///tmp/a%23b.txt')
assert.equal(api.read(offer({'text/x-moz-url': 'https://example.org/image\nimage title'})).urls.length, 1)
assert.equal(api.imageSource('<a href="https://example.org"><img src="https://example.org/small.png" srcset="https://example.org/a.png 1x, https://example.org/b.png?a=1&amp;b=2 2x"></a>'), 'https://example.org/b.png?a=1&b=2')
assert.equal(api.imageSource('<img src="relative.png">'), '')
assert.equal(api.read(offer({'text/uri-list': 'https://example.org/cat.png'})).image, 'https://example.org/cat.png')
const bytes = Uint8Array.from([137, 80, 78, 71, 0, 255])
assert.equal(api.read({formats:['image/png'], getDataAsArrayBuffer: () => bytes.buffer, getDataAsString: () => ''}).image, 'data:application/octet-stream;base64,' + Buffer.from(bytes).toString('base64'))
assert.equal(api.mime({kind:'text', text:'words'})['text/plain'], 'words')
assert.equal(api.mime({kind:'file', uri:'file:///tmp/a%23b'})['text/uri-list'], 'file:///tmp/a%23b\r\n')
const read = []
api.prefetch({formats:['image/png', 'text/uri-list', 'application/octet-stream;name="a.png"'], getDataAsArrayBuffer: f => read.push(f)})
assert.equal(read.length, 3, 'prefetch browser formats before Niri finishes the drop')
console.log('SHELF_DROP_PASS')
