const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict')
function load(name) { const box = {}; vm.runInNewContext(fs.readFileSync(`services/companion/${name}.js`, 'utf8'), box); return box }
const P = load('NaomiPresence'), R = load('NaomiReminders'), L = load('NaomiLines').lines
assert.equal(P.present(false, false, false), true)
assert.equal(P.present(false, true, false), false)
assert.equal(P.present(false, true, true), true, 'playing media keeps presence active')
assert.equal(P.present(true, false, true), false, 'screen lock overrides playback')
let r = R.create(L)
assert.equal(r.next.eyes, 1200)
assert.equal(r.next.water, 3600)
assert.equal(r.next.move, 3600)
R.tick(r, 1100, {present:true, cloud:'busy'})
R.tick(r, 9000, {present:false, cloud:'free'})
assert.equal(r.workTime, 1100)
assert.equal(r.queue.length, 0, 'absence does not trigger reminders')
assert.equal(R.tick(r, 99, {present:true, cloud:'free'}), '')
assert(R.tick(r, 1, {present:true, cloud:'free'}))
assert.equal(r.kind, 'eyes')
r = R.create(L)
R.tick(r, 600, {present:true, cloud:'busy'})
R.configure(r, {eyes: 15, water: 90, move: 30})
assert.equal(r.next.eyes, 900, 'changing intervals preserves elapsed time')
assert.equal(r.next.water, 5400)
assert.equal(r.next.move, 1800)
assert.equal(R.tick(r, 299, {present:true, cloud:'free'}), '')
assert(R.tick(r, 1, {present:true, cloud:'free'}))
assert.equal(r.kind, 'eyes')
console.log('NAOMI_PRESENCE_PASS')
