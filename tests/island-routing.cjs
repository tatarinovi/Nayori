const fs = require('fs'), vm = require('vm'), assert = require('assert')
const context = {}
vm.createContext(context)
vm.runInContext(fs.readFileSync('services/ui/IslandRouting.js', 'utf8').replace(/^\.pragma.*$/m, ''), context)
const { topEnabled, relocationReserve, companionOutput, primaryFirst } = context
const screens = ['DP-1', 'DP-2', 'HDMI-A-1']

assert.equal(topEnabled('', screens, false, false, ''), false)
assert.equal(topEnabled('DP-2', screens, false, true, 'HDMI-A-1'), true)
assert.equal(topEnabled('DP-1', screens, true, false, 'DP-2'), true)
assert.equal(topEnabled('DP-2', screens, true, false, 'DP-2'), false)
assert.equal(topEnabled('DP-2', screens, true, true, ''), false)
assert.equal(topEnabled('DP-2', screens, true, true, 'DP-1'), false)
assert.equal(topEnabled('DP-2', screens, true, true, 'GONE'), false)
assert.equal(topEnabled('DP-1', screens, true, true, 'GONE'), true)
assert.equal(topEnabled('DP-2', screens, true, true, 'DP-2'), true)
assert.equal(topEnabled('HDMI-A-1', screens, true, true, 'DP-2'), false)
assert.equal(topEnabled('HDMI-A-1', screens, true, true, 'HDMI-A-1'), true)
assert.equal(topEnabled('DP-1', screens, true, true, 'HDMI-A-1'), true)

assert.equal(topEnabled('', ['', 'DP-2'], true, true, 'DP-2'), false)
assert.equal(topEnabled('DP-2', ['', 'DP-2'], true, true, 'DP-2'), true)
assert.equal(relocationReserve(false, 64, 64), 0)
assert.equal(relocationReserve(true, 0, 64), 64)
assert.equal(relocationReserve(true, 100, 64), 100)
assert.equal(relocationReserve(true, -4, 64), 64)
assert.equal(relocationReserve(true, 0, 0), 0)
assert.equal(companionOutput(screens, 'primary', false, ''), 'DP-1')
assert.equal(companionOutput(screens, 'primary', true, 'HDMI-A-1'), 'HDMI-A-1')
assert.equal(companionOutput(screens, 'primary', true, 'GONE'), 'DP-1')
assert.equal(companionOutput(screens, 'secondary', true, 'HDMI-A-1'), 'DP-2')
assert.equal(companionOutput(screens, 'secondary', false, ''), 'DP-2')
assert.equal(companionOutput(['DP-1'], 'secondary', true, 'DP-2'), 'DP-1')
assert.equal(companionOutput(['DP-1', ''], 'secondary', false, ''), 'DP-1')
assert.equal(companionOutput(screens, 'elsewhere', true, 'DP-2'), 'DP-2')

assert.deepEqual(Array.from(primaryFirst(screens, [{name: 'DP-2', focusAtStartup: true}])), ['DP-2', 'DP-1', 'HDMI-A-1'])
assert.deepEqual(Array.from(primaryFirst(screens, [{name: 'GONE', focusAtStartup: true}])), screens)
assert.deepEqual(Array.from(primaryFirst(screens, [{name: 'DP-2', focusAtStartup: true, off: true}])), screens)
assert.deepEqual(Array.from(primaryFirst(screens, [])), screens)
assert.equal(companionOutput(primaryFirst(screens, [{name: 'DP-2', focusAtStartup: true}]), 'primary', false, ''), 'DP-2')
assert.equal(topEnabled('DP-2', primaryFirst(screens, [{name: 'DP-2', focusAtStartup: true}]), true, false, ''), true)

console.log('ISLAND_ROUTING_PASS')
