const fs = require('fs'), vm = require('vm'), assert = require('assert')
const events = {}
vm.createContext(events)
vm.runInContext(fs.readFileSync('services/companion/NaomiInteractionEvents.js', 'utf8'), events)

const yandex = playing => ({ identity: 'Yandex Music', isPlaying: playing })
const spotify = { identity: 'Spotify', isPlaying: true }
const browser = (url, playing = true) => ({ identity: 'Firefox', trackUrl: url, isPlaying: playing })
let s = events.create()
assert.equal(events.music(s, [yandex(true)]), '', 'startup playing snapshot is silent')
assert.equal(events.music(s, [yandex(true), spotify]), '', 'another player does not change Yandex playback')
assert.equal(events.music(s, [yandex(false), spotify]), 'musicStop', 'pause is detected while another player keeps playing')
assert.equal(events.music(s, [yandex(false)]), '')
assert.equal(events.music(s, [yandex(true)]), 'musicStart')
assert.equal(events.music(s, []), 'musicStop', 'closing the playing client stops music')
assert.equal(events.music(s, []), '')
assert.equal(events.music(s, [spotify]), '', 'other apps never start Yandex music')
assert.equal(events.music(s, [yandex(false)]), '', 'opening a paused app is silent')
assert.equal(events.music(s, [yandex(true), yandex(true)]), 'musicStart')
assert.equal(events.music(s, [yandex(false), yandex(true)]), '', 'one remaining playing Yandex source preserves playback')
assert.equal(events.music(s, [browser('https://music.yandex.ru/album/1/track/2')]), '', 'switching Yandex sources is continuous')
assert.equal(events.music(s, [browser('')]), '', 'temporary browser metadata gap between tracks is silent')
assert.equal(events.music(s, [browser('https://music.yandex.ru/album/1/track/3')]), '', 'a new track keeps playing')
assert.equal(events.music(s, [browser('https://example.org/video')]), 'musicStop')
for (const identity of ['Яндекс Музыка', 'Yandex Music']) assert(events.isYandexMusic({ identity }))
for (const desktopEntry of ['ru.yandex.Music', 'com.github.cucumber-sp.yandex-music']) assert(events.isYandexMusic({ desktopEntry }))
assert(events.isYandexMusic({ dbusName: 'org.mpris.MediaPlayer2.yandex-music' }))
for (const domain of ['ru', 'com', 'by', 'kz', 'uz', 'com.tr'])
    assert(events.isYandexMusic(browser(`https://music.yandex.${domain}/album/1`)))
for (const url of ['https://music.yandex.ru.evil.org/song', 'https://example.org/?url=https://music.yandex.ru/', 'https://yandex.ru/search', 'file:///music/yandex.mp3'])
    assert(!events.isYandexMusic(browser(url)), url)
assert(!events.isYandexMusic({ identity: 'Yandex Browser' }))
assert(!events.isYandexMusic(null))

const on = { inside: true, enabled: true }
const off = { inside: false, enabled: true }
s = events.create()
assert.equal(events.hover(s, 1, off), false)
events.move(s, 437, 190)
assert.equal(events.hover(s, 0, on), false)
for (let i = 0; i < 5; i++) assert.equal(events.hover(s, 1, on), false, 'exactly five seconds is silent')
assert.equal(events.hover(s, 0.01, on), true)
assert.equal(events.hover(s, 100, on), false, 'holding still produces one event')
events.move(s, 438, 190)
assert.equal(events.hover(s, 10, on), false, 'moving after a reaction does not rearm the same visit')
events.hover(s, 0, off)
events.move(s, 438, 190)
events.hover(s, 0, on)
assert.equal(events.hover(s, 4, on), false)
events.move(s, 439, 190)
assert.equal(events.hover(s, 4, on), false, 'movement restarts five seconds')
events.move(s, 439, 190)
assert.equal(events.hover(s, 1, on), false, 'identical coordinates preserve the timer')
assert.equal(events.hover(s, 0.01, on), true)
events.hover(s, 0, { inside: true, enabled: false })
events.hover(s, 0, on)
assert.equal(events.hover(s, 5, on), false, 're-enabling establishes a new visit')
assert.equal(events.hover(s, 0.01, on), true)
console.log('Naomi interaction detectors: OK')
