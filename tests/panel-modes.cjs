const fs = require('fs'), vm = require('vm'), assert = require('assert')
const policy = {}
vm.createContext(policy)
vm.runInContext(fs.readFileSync('services/ui/PanelModes.js', 'utf8'), policy)
const { normalize, mode, updated, explicitMode } = policy
assert.equal(JSON.stringify(normalize(null)), '{}')
assert.equal(JSON.stringify(normalize([])), '{}')
assert.equal(JSON.stringify(normalize({bad: [], 'DP-1': {top: 'never', apps: 'auto', future: true}})), '{"DP-1":{"apps":"auto"}}')
assert.equal(mode({}, 'DP-1', 'top', false, false), 'always')
assert.equal(mode({}, 'DP-2', 'top', true, true), 'hidden')
assert.equal(mode({}, 'DP-1', 'apps', true, false), 'auto')
let modes = updated({}, 'DP-1', 'top', 'hidden')
const original = JSON.stringify(modes)
const next = updated(modes, 'DP-2', 'apps', 'auto')
assert.equal(JSON.stringify(modes), original)
assert.equal(mode(next, 'DP-1', 'top', false, false), 'hidden')
assert.equal(mode(next, 'DP-2', 'apps', false, false), 'auto')
assert.equal(mode(next, 'DP-2', 'top', false, false), 'always')
modes = updated(next, 'DP-1', 'top', 'always')
assert.equal(mode(modes, 'DP-1', 'top', true, true), 'always')
assert.equal(mode(modes, 'DP-2', 'apps', false, false), 'auto')
assert.equal(explicitMode(modes, 'disconnected', 'top'), '')
assert.equal(mode(JSON.parse(JSON.stringify(next)), 'DP-2', 'apps', false, false), 'auto')
assert.equal(mode(updated({}, '__proto__', 'status', 'hidden'), '__proto__', 'status', false, false), 'hidden')
console.log('PANEL_MODES_PASS')
assert.equal(JSON.stringify(policy.normalizeReservations({'DP-1': {top: 5, bottom: 999}, 'DP-2': {top: -8, bottom: '24'}})), '{"DP-1":{"top":4,"bottom":200},"DP-2":{"top":0}}')
let reservations = policy.updatedReservation({}, 'DP-1', 64, 72)
reservations = policy.updatedReservation(reservations, 'DP-2', 0, 24)
assert.equal(policy.reservation(reservations, 'DP-1', 'top', 0), 64)
assert.equal(policy.reservation(reservations, 'DP-2', 'top', 64), 0)
assert.equal(policy.reservation(reservations, 'DP-2', 'bottom', 72), 24)
assert.equal(policy.reservation(reservations, 'disconnected', 'bottom', 72), 72)
