const fs = require('fs'), vm = require('vm'), assert = require('assert')
const styles = {}
vm.createContext(styles)
vm.runInContext(fs.readFileSync('islands/workspaces/WorkspaceStyles.js', 'utf8'), styles)
assert.equal(styles.styles.length, 6)
for (const style of styles.styles) assert.equal(styles.normalize(style.key), style.key)
for (const invalid of [null, {}, [], 2, 'future', '__proto__']) assert.equal(styles.normalize(invalid), 'dots')
for (const [n, label] of [[1, '一'], [6, '六'], [10, '十'], [11, '十一'], [20, '二十'], [99, '九十九'], [100, '100']])
    assert.equal(styles.label('kanji', n), label)
assert.equal(styles.label('greek', 6), 'ζ')
assert.equal(styles.label('greek', 24), 'ω')
assert.equal(styles.label('greek', 25), 'α2')
assert.equal(styles.label('numbers', 123), '123')
console.log('WORKSPACE_STYLES_PASS')
