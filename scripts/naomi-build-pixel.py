#!/usr/bin/env python3
"""Build the approved Hoodie #03 indexed sprite for QML, without runtime images.

The approved 140x200 sprite (including the nine face corrections) is the master.
It is partitioned into animation channels without redrawing any visible pixels.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]
source=json.loads((ROOT/'assets/naomi/proposals/hoodie-v3/sprite.json').read_text())
W,H=source['width'],source['height']
raw=np.zeros((H,W),dtype=np.int32)
for x,y,n,c in source['runs']:raw[y,x:x+n]=c
palette=source['palette']

def poly(points):
 im=Image.new('L',(W,H));ImageDraw.Draw(im).polygon(points,fill=1)
 return np.asarray(im,dtype=bool)

head=poly([(34,13),(61,11),(77,18),(82,32),(79,48),(78,61),(70,72),(59,71),(46,63),(32,59),(30,43),(31,27)])
pony=poly([(62,4),(78,4),(92,15),(100,34),(106,55),(116,74),(123,84),(113,92),(96,83),(84,72),(79,61),(76,43),(80,29),(66,16)]) & ~head
ribbon=poly([(65,12),(76,12),(85,22),(88,39),(84,42),(77,29),(70,23),(65,23)])
# Forelocks are dark pixels in front of the neck/hood, never skin or clothing.
locks=poly([(43,50),(49,48),(54,67),(54,80),(48,80),(46,68)]) | poly([(73,46),(78,45),(78,65),(73,77),(69,75),(72,61)])
colors=[];roles=[];ids={}

def rgba(c):return tuple(int(c[k:k+2],16) for k in (1,3,5))
def is_accent(c):
 r,g,b=rgba(c);return b-r>7 and b-g>12 and r>65
def is_skin(c):
 r,g,b=rgba(c);return r-g>12 and r-b>10 and r>90

def colour(c,role):
 key=(c,role)
 if key not in ids:
  ids[key]=len(colors)+1;colors.append(c);roles.append(role)
 return ids[key]

parts={name:np.zeros_like(raw) for name in ['ponytail','lower','torso','head','locks','ribbon']}
for y,x in zip(*np.nonzero(raw)):
 c=palette[raw[y,x]]
 if ribbon[y,x] and is_accent(c):part='ribbon'
 elif pony[y,x]:part='ponytail'
 elif locks[y,x] and max(rgba(c))<85:part='locks'
 elif head[y,x]:part='head'
 elif y<136:part='torso'
 else:part='lower'
 role='fixed'
 if is_accent(c):role='accent'
 elif part in ('torso','lower') and not is_skin(c):role='clothing'
 parts[part][y,x]=colour(c,role)

# Hidden one-pixel overlaps at the neck and waist keep breathing joints closed.
# At neutral pose, the original pixels on top completely cover these supports.
for upper,under in [('torso','lower'),('head','torso'),('locks','head'),('locks','torso')]:
 top,bottom=parts[upper],parts[under]
 for y,x in zip(*np.nonzero(top)):
  if y+1<H and bottom[y+1,x] and not bottom[y,x]:bottom[y,x]=bottom[y+1,x]

# A blink edits only these two small polygons; the approved nose/mouth stay intact.
left=poly([(47,51),(49,50),(53,51),(56,53),(54,57),(50,57),(47,54)])
right=poly([(62,43),(66,42),(70,43),(72,45),(70,48),(67,50),(63,48)])
closed={}
skin=colour('#fad1bb','fixed');lash=colour('#382b37','fixed')
for y,x in zip(*np.nonzero((left|right)&(raw>0))):closed[(int(x),int(y))]=skin
for x,y in [(48,54),(49,55),(50,55),(51,55),(52,55),(53,54),(54,54),
            (63,46),(64,47),(65,47),(66,47),(67,47),(68,46),(69,46),(70,45)]:closed[(x,y)]=lash

def runs(grid):
 result=[]
 for y,row in enumerate(grid):
  x=0
  while x<W:
   end=x+1
   while end<W and row[end]==row[x]:end+=1
   if row[x]:result.append([x,y,end-x,int(row[x])])
   x=end
 return result
encoded={k:runs(v) for k,v in parts.items()}
header='// Generated by scripts/naomi-build-pixel.py from the approved Hoodie #03.\n.pragma library\n'
header+='var width = 140;\nvar height = 200;\n'
header+='var originalPalette = '+json.dumps(['transparent']+colors)+';\n'
header+='var colorRoles = '+json.dumps(['transparent']+roles)+';\n'
header+='var parts = '+json.dumps(encoded,separators=(',',':'))+';\n'
header+='var closedEyes = '+json.dumps([[x,y,c] for (x,y),c in closed.items()],separators=(',',':'))+';\n'
header+='var headZone = {x:31,y:13,w:50,h:60};\nvar bubblePoint = {x:59,y:2};\n'
header+=(ROOT/'scripts/naomi-pixel-runtime.js').read_text()
(ROOT/'surfaces/companion/NaomiPixelArt.js').write_text(header)
print('NAOMI_PIXEL_BUILD',len(colors),'palette entries',sum(map(len,encoded.values())),'runs')
