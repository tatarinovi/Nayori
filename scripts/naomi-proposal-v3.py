#!/usr/bin/env python3
"""Encode approved sheet #03 as static indexed pixel data for an isolated QML proof.

Deterministic sampling, not a redrawing: source image pixels supply face and body.
The source sheet is an authoring reference only. The QML proof reads only JS data.
"""
from pathlib import Path
from collections import deque
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/naomi/proposals/hoodie-v3'
source = Image.open(OUT / 'source-sheet.png').convert('RGB')
# Full third character, excluding the label. A known-empty perimeter models the
# sheet's gently varying graphite backdrop without changing any foreground RGB.
crop = source.crop((1250, 110, 1720, 850))
rgb = np.array(crop)
h,w = rgb.shape[:2]
y,x = np.mgrid[:h,:w]
xn,yn = x/w,y/h
basis = np.stack([np.ones_like(xn),xn,yn,xn*xn,yn*yn,xn*yn],axis=-1)
edge = (x<8)|(x>=w-8)|(y<8)|(y>=h-8)
coeff = np.linalg.lstsq(basis[edge],rgb[edge],rcond=None)[0]
background = basis@coeff
candidate = np.max(np.abs(rgb-background),axis=2)>9
# Border-connected background stays transparent; enclosed quiet colour areas are
# inside the figure. Keep only the main connected component, discarding noise.
seen = candidate.copy()
queue = deque()
for xx in range(w):
    for yy in (0,h-1):
        if not seen[yy,xx]:seen[yy,xx]=True;queue.append((yy,xx))
for yy in range(h):
    for xx in (0,w-1):
        if not seen[yy,xx]:seen[yy,xx]=True;queue.append((yy,xx))
while queue:
    yy,xx=queue.popleft()
    for dy,dx in ((-1,0),(1,0),(0,-1),(0,1)):
        ny,nx=yy+dy,xx+dx
        if 0<=ny<h and 0<=nx<w and not seen[ny,nx]:
            seen[ny,nx]=True;queue.append((ny,nx))
solid = candidate | ~seen
visited=np.zeros_like(solid)
components=[]
for yy,xx in zip(*np.nonzero(solid)):
    if visited[yy,xx]:continue
    visited[yy,xx]=True;queue=deque([(yy,xx)]);points=[]
    while queue:
        py,px=queue.popleft();points.append((py,px))
        for dy,dx in ((-1,0),(1,0),(0,-1),(0,1)):
            ny,nx=py+dy,px+dx
            if 0<=ny<h and 0<=nx<w and solid[ny,nx] and not visited[ny,nx]:
                visited[ny,nx]=True;queue.append((ny,nx))
    components.append(points)
mask=np.zeros_like(solid)
for yy,xx in max(components,key=len):mask[yy,xx]=True
ys,xs=np.nonzero(mask)
box=(int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1))
rgba=np.dstack([rgb,np.uint8(mask)*255])
figure=Image.fromarray(rgba).crop(box)
scale=min(132/figure.width,192/figure.height)
size=(round(figure.width*scale),round(figure.height*scale))
figure=figure.resize(size,Image.Resampling.NEAREST)
canvas=Image.new('RGBA',(140,200))
canvas.paste(figure,((140-size[0])//2,200-size[1]-4))
# 64 indexed colours retain small facial features; no dither invents extra dots.
indexed=canvas.quantize(colors=64,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
rgba=np.array(indexed.convert('RGBA'))
fixed=[];lookup={};pixels=[]
for row in rgba:
    output=[]
    for r,g,b,a in row:
        if a<128:output.append(0);continue
        key=f'#{r:02x}{g:02x}{b:02x}'
        if key not in lookup:lookup[key]=len(fixed)+1;fixed.append(key)
        output.append(lookup[key])
    pixels.append(output)
# Intentional grid-level corrections remain separate from source sampling: these
# tiny nose/lip clusters survive the downsampling without changing the face shape.
for feature in json.loads((OUT/'face-details.json').read_text())['features']:
    colour=feature['color']
    if colour not in lookup:
        lookup[colour]=len(fixed)+1
        fixed.append(colour)
    for xx,yy in feature['pixels']:
        assert 0<=xx<140 and 0<=yy<200 and pixels[yy][xx]!=0
        pixels[yy][xx]=lookup[colour]
runs=[]
for yy,row in enumerate(pixels):
    xx=0
    while xx<140:
        end=xx+1
        while end<140 and row[end]==row[xx]:end+=1
        if row[xx]:runs.append([xx,yy,end-xx,row[xx]])
        xx=end
manifest={'width':140,'height':200,'palette':['transparent']+fixed,'runs':runs}
(OUT/'sprite.json').write_text(json.dumps(manifest,separators=(',',':'))+'\n')
(OUT/'Sprite.js').write_text('// Generated by scripts/naomi-proposal-v3.py; static approval proof.\n.pragma library\n'
    'var width = 140;\nvar height = 200;\nvar palette = '+json.dumps(manifest['palette'])+';\n'
    'var runs = '+json.dumps(runs,separators=(',',':'))+';\n')
print('NAOMI_PROPOSAL_ENCODED',len(fixed),'colours',len(runs),'runs',size)
